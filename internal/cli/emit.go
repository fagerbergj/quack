package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// InitAnswers is the collected wizard output for `quack server init` (and the
// local branch of `quack init`). The wizard (internal/wizard) populates this;
// EmitServerConfig turns it into a quack.yaml. Kept here, not in the wizard
// package, so it's testable without constructing a Huh form.
// The yaml tags are also what `server init --answers <file>` unmarshals into.
type InitAnswers struct {
	Endpoint string `yaml:"endpoint"` // LLM endpoint (OpenAI-compatible base URL)
	APIKey   string `yaml:"api_key"`  // typed; emitted as ${QUACK_LLM_API_KEY} (the export is printed)

	MainModel   string `yaml:"main_model"`   // orchestrator + researcher (the common case)
	JudgeModel  string `yaml:"judge_model"`  // blank ⇒ trust gate disabled
	EmbedModel  string `yaml:"embed_model"`  // blank ⇒ semantic memory disabled
	VisionModel string `yaml:"vision_model"` // blank ⇒ no image-reader agent
	AudioModel  string `yaml:"audio_model"`  // blank ⇒ no media-reader agent

	// Stores - each kind picks the adapter; url is the connection (blank ⇒ the
	// emitter fills the no-docker default for that kind).
	SessionKind string `yaml:"session_kind"` // sqlite | postgres
	SessionURL  string `yaml:"session_url"`
	MemoryKind  string `yaml:"memory_kind"` // sqlite | qdrant  (blank when EmbedModel empty)
	MemoryURL   string `yaml:"memory_url"`
	SearchKind  string `yaml:"search_kind"` // exa | searxng   (blank when web search off)
	SearchURL   string `yaml:"search_url"`
	FetchKind   string `yaml:"fetch_kind"` // direct | crawl4ai (blank when web fetch off)
	FetchURL    string `yaml:"fetch_url"`

	WebSearch bool `yaml:"web_search"` // optional-feature toggles (drive which stores are emitted)
	WebFetch  bool `yaml:"web_fetch"`

	// Coding - emit the coding agents (code-implementer/explorer/reviewer) plus
	// the workspace section they need (sandbox + run_command/run_code guards).
	Coding     bool   `yaml:"coding"`
	CoderModel string `yaml:"coder_model"` // blank ⇒ reuse MainModel
	Sandbox    string `yaml:"sandbox"`     // workspace.sandbox: bwrap | none (blank ⇒ bwrap, the server default)
}

// LoadInitAnswersFile applies env prefill first, then the file's values on
// top - an --answers file only has to name what differs from the environment.
func LoadInitAnswersFile(path string) (InitAnswers, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return InitAnswers{}, fmt.Errorf("read --answers %s: %w", path, err)
	}
	a := InitAnswers{WebSearch: true, WebFetch: true}
	PrefillFromEnv(&a)
	if err := yaml.Unmarshal(raw, &a); err != nil {
		return InitAnswers{}, fmt.Errorf("parse --answers %s: %w", path, err)
	}
	return a, nil
}

// WriteServerConfig writes a to outPath and prints the confirmation + env
// exports - the shared tail for both the wizard and a headless --answers init.
func WriteServerConfig(a InitAnswers, outPath string) error {
	if dir := filepath.Dir(outPath); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("create %s: %w", dir, err)
		}
	}
	if err := os.WriteFile(outPath, []byte(EmitServerConfig(a)), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", outPath, err)
	}
	fmt.Printf("\n✓ Wrote %s\n", outPath)
	for _, line := range EnvExports(a) {
		fmt.Println(line)
	}
	return nil
}

// EmitServerConfig renders a complete quack.yaml from the answers. Secrets
// (API key, any DB password in a URL) are emitted as ${ENV} references and the
// caller prints the matching export commands. Non-secrets (endpoint, model
// names) are hardcoded - the wizard output works with no env setup beyond the
// one secret. The agent roster is tailored: media-reader only with an audio
// model, image-reader only with a vision model.
func EmitServerConfig(a InitAnswers) string {
	var b strings.Builder
	b.WriteString("# Quack configuration - generated by `quack server init`.\n")
	b.WriteString("# The API key is read from ${QUACK_LLM_API_KEY}; set it with the export the wizard prints.\n\n")

	b.WriteString("providers:\n  default:\n    kind: openai\n")
	fmt.Fprintf(&b, "    endpoint: %s\n    api_key: ${QUACK_LLM_API_KEY}\n\n", a.Endpoint)

	b.WriteString("stores:\n")
	emitStore(&b, "default_postgres", a.SessionKind, a.SessionURL)
	if a.EmbedModel != "" {
		emitStore(&b, "default_vector", a.MemoryKind, a.MemoryURL)
	}
	b.WriteString("\n")

	b.WriteString("session:\n  store: default_postgres\n")
	if a.EmbedModel == "" {
		b.WriteString("  # semantic memory is off (no embedding model was selected)\n")
	}
	b.WriteString("\n")

	fmt.Fprintf(&b, "orchestrator:\n  provider: default\n  model: %s\n", a.MainModel)
	emitOrchTools(&b, a)
	b.WriteString("\n")

	emitModels(&b, a)

	b.WriteString("agents:\n")
	researcherTools := baseTools(a)
	if a.EmbedModel != "" {
		researcherTools = append(researcherTools, "stage_memory")
	}
	emitAgent(&b, "web-researcher", a.MainModel, 65536, "["+strings.Join(researcherTools, ", ")+"]")
	emitAgent(&b, "synthesizer", a.MainModel, 65536, "[]")
	if a.AudioModel != "" {
		emitAgent(&b, "media-reader", a.AudioModel, 32768, "[]")
		b.WriteString("    inputs: [text, image, audio]\n")
	}
	if a.VisionModel != "" {
		emitAgent(&b, "image-reader", a.VisionModel, 32768, "[]")
		b.WriteString("    inputs: [text, image]\n")
	}
	if a.Coding {
		emitCodingAgents(&b, a)
	}
	b.WriteString("\n")

	b.WriteString("tools:\n")
	if toolEnabled(a.WebSearch, a.SearchKind) {
		emitTool(&b, "web_search", a.SearchKind, a.SearchURL)
	}
	if toolEnabled(a.WebFetch, a.FetchKind) {
		emitTool(&b, "web_fetch", a.FetchKind, a.FetchURL)
	}
	if a.EmbedModel != "" {
		b.WriteString("  stage_memory:\n    store: default_vector\n")
	}
	b.WriteString("\n")

	if a.JudgeModel != "" {
		b.WriteString("gates:\n  rubric_path: config/rubric.md\n  deterministic_checks:\n    max_rounds: 1\n")
		fmt.Fprintf(&b, "  judge:\n    provider: default\n    model: %s\n    max_rounds: 1\n    threshold: 0.6\n\n", a.JudgeModel)
	}

	b.WriteString("dag:\n  max_active_nodes: 2\n\n")
	if a.Coding {
		emitWorkspace(&b, a)
	}
	b.WriteString("server:\n  addr: \":8080\"\n")
	return b.String()
}

// emitCodingAgents renders the three coding agents, mirroring the reference
// config/quack.yaml roster: each is an EXTERNAL agent over ACP (the pi-acp shim
// drives the model bound here), explorer and reviewer read-only. quack has no
// native repo/exec tools - they left the registry with the ACP switch - so
// these agents carry no tools: list at all.
func emitCodingAgents(b *strings.Builder, a InitAnswers) {
	model := a.CoderModel
	if model == "" {
		model = a.MainModel
	}
	acp := func(readOnly bool) {
		b.WriteString("    acp:\n      command: [node, /usr/local/lib/pi-acp/pi-acp.mjs]   # needs node + the pi-acp shim (tools/pi-acp/ in the repo, /usr/local/lib/pi-acp/ in the image)\n")
		if readOnly {
			b.WriteString("      read_only: true\n")
		}
	}
	emitAgent(b, "code-implementer", model, 65536, "")
	b.WriteString("    judge_rounds: 8   # coding converges via the judge+revise grind\n")
	acp(false)
	emitAgent(b, "code-explorer", model, 65536, "")
	b.WriteString("    judge_rounds: 2\n")
	acp(true)
	emitAgent(b, "code-reviewer", model, 65536, "")
	b.WriteString("    judge_rounds: 2\n")
	acp(true)
}

// emitWorkspace renders the workspace section the coding agents need: the
// sandbox mode the ACP child processes run inside (bwrap needs bubblewrap
// installed; none = no OS boundary).
func emitWorkspace(b *strings.Builder, a InitAnswers) {
	sandbox := a.Sandbox
	if sandbox == "" {
		sandbox = "bwrap"
	}
	fmt.Fprintf(b, "workspace:\n  sandbox: %s\n\n", sandbox)
}

// EnvExports is the set of `export` lines the wizard prints so the emitted
// ${ENV} references resolve. Only secrets get env refs (the API key); the
// endpoint and model names are hardcoded into the config, so there's nothing
// to export beyond the key.
func EnvExports(a InitAnswers) []string {
	var out []string
	if a.APIKey != "" {
		out = append(out, fmt.Sprintf("export QUACK_LLM_API_KEY=%q", a.APIKey))
	}
	return out
}

func emitStore(b *strings.Builder, name, kind, url string) {
	if kind == "" {
		kind = "sqlite"
	}
	if url == "" {
		url = DefaultBackendURL(kind)
	}
	fmt.Fprintf(b, "  %s:\n    kind: %s\n    url: %s\n", name, kind, url)
}

func emitTool(b *strings.Builder, name, kind, url string) {
	if kind == "" {
		return
	}
	if url == "" {
		url = DefaultBackendURL(kind)
	}
	if url == "" {
		fmt.Fprintf(b, "  %s:\n    kind: %s\n", name, kind)
		return
	}
	fmt.Fprintf(b, "  %s:\n    kind: %s\n    url: %s\n", name, kind, url)
}

// emitModels renders the models: registry entry for every distinct model
// referenced below - by an agent, gates.judge, or the vector store's
// embedder - each such reference must resolve to a registry entry.
func emitModels(b *strings.Builder, a InitAnswers) {
	coder := a.CoderModel
	if coder == "" {
		coder = a.MainModel
	}
	seen := map[string]bool{}
	b.WriteString("models:\n")
	for _, mr := range []struct{ model, role string }{
		{a.MainModel, "worker"}, {a.AudioModel, "worker"}, {a.VisionModel, "worker"}, {coder, "worker"},
		{a.JudgeModel, "judge"}, {a.EmbedModel, "embed"},
	} {
		if mr.model == "" || seen[mr.model] {
			continue
		}
		seen[mr.model] = true
		fmt.Fprintf(b, "  %s:\n    provider: default\n    role: %s\n", mr.model, mr.role)
	}
	b.WriteString("\n")
}

// toolEnabled mirrors emitTool's own gate: a toggle with no kind chosen
// emits nothing under `tools:`, so nothing may reference the tool either.
func toolEnabled(toggle bool, kind string) bool {
	return toggle && kind != ""
}

// baseTools is shared by the orchestrator and web-researcher: an agent
// referencing web_search/web_fetch when `tools:` doesn't define it fails at boot.
func baseTools(a InitAnswers) []string {
	var t []string
	if toolEnabled(a.WebSearch, a.SearchKind) {
		t = append(t, "web_search")
	}
	if toolEnabled(a.WebFetch, a.FetchKind) {
		t = append(t, "web_fetch")
	}
	return append(t, "summarize", "current_date")
}

func emitOrchTools(b *strings.Builder, a InitAnswers) {
	tools := baseTools(a)
	if a.EmbedModel != "" {
		tools = append(tools, "commit_memory")
	}
	fmt.Fprintf(b, "  tools: [%s]\n", strings.Join(tools, ", "))
}

// emitAgent renders one agent; a blank tools omits the key (ACP agents have none).
func emitAgent(b *strings.Builder, name, model string, ctx int, tools string) {
	fmt.Fprintf(b, "  %s:\n    bundle: agents/%s\n    provider: default\n    model: %s\n    context_window: %d\n",
		name, name, model, ctx)
	if tools != "" {
		fmt.Fprintf(b, "    tools: %s\n", tools)
	}
}

// DefaultBackendURL is the no-docker default connection for a store/tool kind,
// applied when the user leaves the URL blank - and surfaced live as the URL
// field's placeholder in the wizard, so the default tracks the selected kind.
// Kinds that need no URL (exa is API-key based; direct fetches in-process)
// return "".
func DefaultBackendURL(kind string) string {
	switch kind {
	case "sqlite":
		return "quack.db"
	case "qdrant":
		return "localhost:6334"
	case "postgres":
		return "postgres://quack:quack@localhost:5432/quack?sslmode=disable"
	case "searxng":
		return "http://localhost:8080"
	case "crawl4ai":
		return "http://localhost:11235"
	default: // exa, direct - no URL needed
		return ""
	}
}
