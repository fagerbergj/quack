#!/usr/bin/env bash
# Regenerate all code from the OpenAPI spec (single source of truth):
#   - the Go chi-server + models (oapi-codegen)
#   - the TypeScript client (openapi-ts)
set -euo pipefail
cd "$(dirname "$0")/.."

echo "==> Go server types (oapi-codegen)"
go generate ./internal/schema/...

echo "==> TypeScript client (openapi-ts)"
( cd frontend && npm run generate )

echo "==> API compatibility version (openapi.yaml info.x-api-version)"
# After openapi-ts: it empties src/generated on every run.
api_version=$(sed -n 's/^  x-api-version: *\([0-9][0-9]*\)$/\1/p' openapi.yaml)
api_min_version=$(sed -n 's/^  x-api-min-version: *\([0-9][0-9]*\)$/\1/p' openapi.yaml)
[ -n "$api_version" ] && [ -n "$api_min_version" ] || { echo "openapi.yaml info lacks x-api-version/x-api-min-version" >&2; exit 1; }
printf '%s\n' "// Code generated by scripts/generate.sh from openapi.yaml info. DO NOT EDIT." "" "package schema" "" \
  "// APIVersion and APIMinVersion are info.x-api-version and info.x-api-min-version." \
  "const (" "	APIVersion    = $api_version" "	APIMinVersion = $api_min_version" ")" > internal/schema/apiversion.gen.go
printf '%s\n' "// Code generated by scripts/generate.sh from openapi.yaml info.x-api-version. DO NOT EDIT." \
  "export const API_VERSION = $api_version" > frontend/src/generated/apiVersion.gen.ts

echo "Done."
